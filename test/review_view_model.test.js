const assert = require('assert');
const service = require('../src/services/reviewViewModel.js');
const base = { jiaPlaceId: 'qa-a', creator: 'u1', content: '很好吃', rating: 'good', createdAt: '2026-09-01T00:00:00Z', status: 'approved' };
const reviews = [base, { ...base, id: 'r2', creator: 'u2', rating: 'fair', content: '普通', createdAt: '2026-09-02T00:00:00Z' }, { ...base, id: 'r3', creator: 'u3', rating: 'bad', status: 'rejected' }, { ...base, id: 'other', jiaPlaceId: 'qa-b', creator: 'u4', rating: 1 }];
const normalized = service.forRestaurant(reviews, 'qa-a');
assert.strictEqual(normalized.length, 2);
assert.deepStrictEqual(service.aggregate(normalized).distribution, { 5: 1, 4: 0, 3: 1, 2: 0, 1: 0 });
assert.strictEqual(service.aggregate(normalized).average, 4);
assert.strictEqual(service.aggregate([]).average, null);
assert.strictEqual(service.aggregate([]).count, 0);
assert.strictEqual(service.canCreate(reviews, 'qa-a', 'u1'), false);
assert.strictEqual(service.canCreate(reviews, 'qa-a', 'u9'), true);
assert.strictEqual(service.sort(normalized, 'highest')[0].userId, 'u1');
assert.strictEqual(service.sort(normalized, 'lowest')[0].userId, 'u2');
const helpful = service.toggleHelpful(service.normalize({ ...base, id: 'r1', userId: 'u1', helpfulBy: [] }), 'u2');
assert.strictEqual(helpful.review.helpfulCount, 1);
assert.strictEqual(service.toggleHelpful(helpful.review, 'u1').changed, false);
assert.ok(service.escapeText('<script>alert(1)</script>').includes('&lt;script&gt;'));
assert.strictEqual(service.validateDraft({ rating: 5, text: '🙂' }).valid, true);
assert.strictEqual(service.validateDraft({ rating: 5.5, text: 'x' }).valid, false);
assert.ok(service.formatDate('2026-09-30T16:30:00Z').includes('10/1') || service.formatDate('2026-09-30T16:30:00Z').includes('10月1日'));
console.log('✅ review view model, rating, identity, helpful and safety checks passed');
