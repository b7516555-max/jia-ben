const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const version = fs.readFileSync(path.join(root, 'src/config/appVersion.js'), 'utf8');
const notes = fs.readFileSync(path.join(root, 'src/config/releaseNotes.js'), 'utf8');
assert.ok(html.includes('✨ 吃貨情報解鎖'), 'Detail completeness title uses positive copy');
assert.ok(html.includes('✨ 待解鎖，點此補充'), 'Missing fields use positive contribution copy');
assert.ok(html.includes('項已解鎖'), 'Completeness score uses unlocked wording');
assert.ok(!html.includes('缺漏，點此補上'), 'Legacy negative detail copy is removed');
assert.ok(version.includes("JIA_BEN_VERSION = 'v149'") && notes.includes('v149'), 'v149 is configured');
assert.ok(html.includes('jia-manual-location-modal') || html.includes('openManualLocationPicker'), 'Manual location picker is wired');
console.log('✅ v149 location and maps contract baseline passed');
