const assert = require('assert');
const registry = require('../src/services/openDataSourceRegistry.js');
const adapters = require('../src/services/restaurantSourceAdapters.js');
const matching = require('../src/services/restaurantMatching.js');
const canonical = require('../src/services/canonicalRestaurant.js');
const provider = require('../src/services/mapProvider.js');
assert.strictEqual(registry.get('taiwan_tourism_restaurant').enabled, true);
assert.strictEqual(registry.get('overture_places').enabled, false);
assert.strictEqual(registry.get('foursquare_os_places').enabled, false);
assert.strictEqual(registry.get('openstreetmap_poi').license, 'ODbL-1.0');
const candidate = adapters.normalizeTourism({ RestaurantID:'r1', RestaurantName:'測試店', PositionLat:22.62, PositionLon:120.31, PostalAddress:{City:'高雄市',Town:'苓雅區',StreetAddress:'中正一路1號'}, Telephones:[{Tel:'07-1234567'}], ServiceTimeInfo:'11:00–21:00' });
assert.strictEqual(adapters.validate(candidate).valid, true);
assert.strictEqual(adapters.validate({name:'bad',latitude:0,longitude:0}).valid, false);
const score = matching.score({name:'測試店',address:'高雄市苓雅區中正一路1號',phone:'071234567',latitude:22.62,longitude:120.31}, {name:'測試店',address:'高雄市苓雅區中正一路1號',phone:'071234567',latitude:22.6201,longitude:120.3101});
assert.strictEqual(score.decision, 'AUTO_MATCH');
assert.strictEqual(canonical.preserveId({restaurantId:'jia_1',communityReviews:[{id:1}]},{restaurantId:'src:r1',name:'測試店'}).restaurantId,'jia_1');
assert.throws(() => provider.assertProvider({}), /MAP_PROVIDER_CONTRACT_MISSING/);
assert.ok(provider.METHODS.includes('onViewportChange'));
console.log('✅ open-data registry, adapters, canonical ID and map provider contract checks passed');
